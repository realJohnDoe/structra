"""structra-parse-rust: Rust `mod` and `use` resolution on tree-sitter-rust.

Resolution rules (see docs/research/import-resolution.md, section 3):

- Crates and their root files come from `cargo.py`. Each crate's module tree
  is built from its root by following `mod` declarations, taking the union
  over `cfg`s: a module declared twice (say under two `cfg`s with different
  `#[path]`s) has both files.
- `mod x;` loads `x.rs` or `x/mod.rs` from the declaring module's directory:
  the file's own directory for a crate root or a `mod.rs`, `a/` for a
  non-mod-rs file `a.rs`, plus `m/` for each enclosing inline `mod m { }`.
  `#[path = "p"]` is relative to the declaring file's directory, or to the
  enclosing inline module's directory; a file loaded through `#[path]` acts as
  a `mod.rs`. Each `mod` declaration is an edge from the declaring file to the
  loaded file.
- Items inside macro invocations (`cfg_rt! { mod a; pub use a::B; }`) count:
  a macro's token tree is parsed again as Rust. `macro_rules!` bodies don't
  count.
- `use` trees and paths in code (`crate::a::f()`, `super::T`) resolve to the
  longest prefix that is a module, and link to its file (grimp's rule for
  Python). A path starts at the crate root (`crate`), the current module
  (`self`), its parent (`super`), a child module of the current module, or
  the root of a library crate of this repository, by its crate name. Other
  paths (the standard library, external crates, enum variants, ...) are
  ignored. In edition 2015 a `use` path that starts with a name, or `::`,
  starts at the crate root.
- A file that no crate's module tree reaches is treated as a crate root of
  its own (edition 2021), as `rustc file.rs` would: shallower files first,
  and `lib.rs`, `main.rs` and `mod.rs` before their siblings.
- Reported on stderr as unresolved: a `mod` declaration with no In-scope
  File, and a `super` beyond the crate root.

Not seen: modules and paths generated by macros or build scripts, `include!`,
and names brought into scope by another `use` (`use crate::a; use a::b;`
links only to `a`). tree-sitter recovers from syntax errors, so a file that
doesn't fully parse keeps the edges of the parts that do.
"""

import posixpath
import sys
from dataclasses import dataclass, field
from pathlib import Path

import tree_sitter_rust
from tree_sitter import Language as TreeSitterLanguage
from tree_sitter import Node, Parser

from .cargo import Crate, crates
from .cli import Diagnostics, Language, run
from .scope import tracked_files

_PARSER = Parser(TreeSitterLanguage(tree_sitter_rust.language()))

# A path: its segments, and the byte offset where it is written.
_Path = tuple[list[str], int]


@dataclass
class _Scan:
    """What one module body declares and refers to."""

    mods: list["_ModDecl"] = field(default_factory=list)
    uses: list[_Path] = field(default_factory=list)
    paths: list[_Path] = field(default_factory=list)  # paths in code


@dataclass
class _ModDecl:
    name: str
    path_attr: str | None
    body: _Scan | None  # an inline module's body
    offset: int


def _segments(node: Node) -> list[str] | None:
    """The segments of a simple path (`a::b::c`, `::a`, `crate::a`), or None."""
    if node.type in ("identifier", "type_identifier", "crate", "self", "super"):
        return [_text(node)]
    if node.type in ("scoped_identifier", "scoped_type_identifier"):
        name = node.child_by_field_name("name")
        if name is None:
            return None
        path = node.child_by_field_name("path")
        if path is None:
            return ["::", _text(name)]
        head = _segments(path)
        return None if head is None else [*head, _text(name)]
    return None


def _text(node: Node) -> str:
    return (node.text or b"").decode("utf-8", errors="replace")


def _use_paths(node: Node, prefix: list[str]) -> list[list[str]]:
    """The paths one use tree names; `a::{self, b}` names `a` and `a::b`."""
    if node.type == "use_as_clause":
        path = node.child_by_field_name("path")
        return _use_paths(path, prefix) if path else []
    if node.type == "use_wildcard":
        inner = next((c for c in node.named_children if c.type != "comment"), None)
        return _use_paths(inner, prefix) if inner else [prefix] if prefix else []
    if node.type in ("scoped_use_list", "use_list"):
        if node.type == "scoped_use_list":
            path = node.child_by_field_name("path")
            if path is not None:
                head = _segments(path)
                if head is None:
                    return []
                prefix = [*prefix, *head]
            elif node.children and node.children[0].type == "::":
                prefix = [*prefix, "::"]
            node = node.child_by_field_name("list") or node
        return [p for child in node.named_children for p in _use_paths(child, prefix)]
    if node.type == "self" and prefix:
        return [prefix]
    segments = _segments(node)
    return [[*prefix, *segments]] if segments else []


def _path_attr(node: Node) -> str | None:
    """The `#[path = "..."]` attribute in front of an item."""
    prev = node.prev_named_sibling
    while prev is not None and prev.type in ("attribute_item", "line_comment", "block_comment"):
        if prev.type == "attribute_item" and prev.named_children:
            attr = prev.named_children[0]
            name, value = attr.named_children[0] if attr.named_children else None, attr.child_by_field_name("value")
            if name is not None and _text(name) == "path" and value is not None and value.type == "string_literal":
                return "".join(_text(c) for c in value.named_children if c.type == "string_content")
        prev = prev.prev_named_sibling
    return None


def _scan(source: bytes) -> _Scan:
    scan = _Scan()
    stack: list[tuple[Node, _Scan, int]] = [(_PARSER.parse(source).root_node, scan, 0)]
    while stack:
        node, into, base = stack.pop()
        kind = node.type
        if kind == "mod_item":
            name = node.child_by_field_name("name")
            if name is None:
                continue
            body = node.child_by_field_name("body")
            inline = _Scan() if body is not None else None
            into.mods.append(_ModDecl(_text(name), _path_attr(node), inline, base + node.start_byte))
            if body is not None and inline is not None:
                stack.extend((child, inline, base) for child in reversed(body.children))
        elif kind == "use_declaration":
            argument = node.child_by_field_name("argument")
            if argument is not None:
                into.uses.extend((p, base + node.start_byte) for p in _use_paths(argument, []))
        elif kind in ("macro_definition", "attribute_item", "inner_attribute_item"):
            continue
        elif kind == "macro_invocation":
            macro = node.child_by_field_name("macro")
            if macro is not None and (segments := _segments(macro)) and len(segments) > 1:
                into.paths.append((segments, base + macro.start_byte))
            tree = next((c for c in node.named_children if c.type == "token_tree"), None)
            if tree is not None and tree.end_byte - tree.start_byte > 2:
                inner = (tree.text or b"")[1:-1]
                stack.append((_PARSER.parse(inner).root_node, into, base + tree.start_byte + 1))
        elif kind in ("scoped_identifier", "scoped_type_identifier") and (segments := _segments(node)):
            into.paths.append((segments, base + node.start_byte))
        else:
            stack.extend((child, into, base) for child in reversed(node.children))
    return scan


@dataclass(eq=False)
class _Module:
    crate: "_CrateTree"
    file: str
    dir: str  # where `mod x;` looks for x.rs and x/mod.rs
    path_base: str  # what `#[path]` is relative to
    scan: _Scan
    parent: "_Module | None" = None
    children: dict[str, list["_Module"]] = field(default_factory=dict)


@dataclass(eq=False)
class _CrateTree:
    edition: str
    root: _Module | None = None
    modules: list[_Module] = field(default_factory=list)


class _Resolver:
    def __init__(self, repo: Path, files: list[str], diagnostics: Diagnostics) -> None:
        self.repo = repo
        self.files = set(files)
        self.diagnostics = diagnostics
        self.scans: dict[str, _Scan] = {}
        self.edges: set[tuple[str, str]] = set()
        self.unresolved: set[tuple[str, str, int]] = set()  # (file, written, offset)
        self.libs: dict[str, list[_Module]] = {}

    def scan(self, file: str) -> _Scan:
        if file not in self.scans:
            try:
                self.scans[file] = _scan((self.repo / file).read_bytes())
            except OSError as e:
                self.diagnostics.parse_failed(file, f"{type(e).__name__}: {e}")
                self.scans[file] = _Scan()
        return self.scans[file]

    def build(self, root: str, edition: str) -> _CrateTree:
        crate = _CrateTree(edition)
        directory = posixpath.dirname(root)
        crate.root = _Module(crate, root, directory, directory, self.scan(root))
        stack = [crate.root]
        while stack:
            module = stack.pop()
            crate.modules.append(module)
            for decl in module.scan.mods:
                child = self.child(module, decl)
                if child is not None:
                    module.children.setdefault(decl.name, []).append(child)
                    stack.append(child)
        return crate

    def child(self, module: _Module, decl: _ModDecl) -> _Module | None:
        if decl.body is not None:
            if decl.path_attr is not None:
                directory = posixpath.normpath(posixpath.join(module.path_base, decl.path_attr))
            else:
                directory = posixpath.join(module.dir, decl.name)
            return _Module(module.crate, module.file, directory, directory, decl.body, module)
        if decl.path_attr is not None:
            file = posixpath.normpath(posixpath.join(module.path_base, decl.path_attr))
            directory = posixpath.dirname(file)
        else:
            candidates = [posixpath.join(module.dir, f"{decl.name}.rs"), posixpath.join(module.dir, decl.name, "mod.rs")]
            file = next((f for f in candidates if f in self.files), candidates[0])
            directory = file[: -len(".rs")] if posixpath.basename(file) != "mod.rs" else posixpath.dirname(file)
        if file not in self.files:
            self.unresolved.add((module.file, f"mod {decl.name}", decl.offset))
            return None
        if self.loops(module, file):
            return None
        self.edges.add((module.file, file))
        return _Module(module.crate, file, directory, posixpath.dirname(file), self.scan(file), module)

    @staticmethod
    def loops(module: _Module, file: str) -> bool:
        """Whether `file` is already a file module on the way up from `module`."""
        current: _Module | None = module
        while current is not None:
            if current.file == file:
                return True
            current = current.parent
        return False

    def resolve(self, module: _Module, path: list[str], offset: int, is_use: bool) -> None:
        crate = module.crate
        assert crate.root is not None
        first, rest = path[0], path[1:]
        current: list[_Module]
        if first == "crate":
            current = [crate.root]
        elif first == "self":
            current = [module]
        elif first == "super":
            current, rest = [module], path
        elif first == "::":
            if not rest:
                return
            if crate.edition == "2015" and rest[0] in crate.root.children:
                current, rest = crate.root.children[rest[0]], rest[1:]
            elif rest[0] in self.libs:
                current, rest = self.libs[rest[0]], rest[1:]
            else:
                return
        else:
            scope = crate.root if is_use and crate.edition == "2015" else module
            current = scope.children.get(first) or self.libs.get(first) or []
            if not current:
                return
        for segment in rest:
            if segment == "super":
                parents = [m.parent for m in current]
                if any(p is None for p in parents):
                    self.unresolved.add((module.file, "::".join(path), offset))
                    return
                following = [p for p in parents if p is not None]
            elif segment == "self":
                continue
            else:
                following = [c for m in current for c in m.children.get(segment, [])]
            if not following:
                break
            current = following
        self.edges.update((module.file, m.file) for m in current)


def _orphan_order(file: str) -> tuple[int, bool, str]:
    return (file.count("/"), posixpath.basename(file) not in ("lib.rs", "main.rs", "mod.rs"), file)


def resolve(repo: Path, files: list[str], diagnostics: Diagnostics) -> list[tuple[str, str]]:
    resolver = _Resolver(repo, files, diagnostics)
    roots: list[Crate] = [c for c in crates(repo, tracked_files(repo)) if c.root in resolver.files]
    trees = []
    for crate in roots:
        tree = resolver.build(crate.root, crate.edition)
        trees.append(tree)
        if crate.lib_name is not None and tree.root is not None:
            resolver.libs.setdefault(crate.lib_name, []).append(tree.root)
    reached = {m.file for tree in trees for m in tree.modules}
    for file in sorted(resolver.files - reached, key=_orphan_order):
        if file not in reached:
            tree = resolver.build(file, "2021")
            trees.append(tree)
            reached |= {m.file for m in tree.modules}
    for tree in trees:
        for module in tree.modules:
            for path, offset in module.scan.uses:
                resolver.resolve(module, path, offset, is_use=True)
            for path, offset in module.scan.paths:
                resolver.resolve(module, path, offset, is_use=False)
    for file, written, _ in sorted(resolver.unresolved):  # once per place, whatever the crates
        diagnostics.unresolved_import(f"{file}: {written}")
    return sorted(resolver.edges)


RUST = Language("rust", frozenset({".rs"}), resolve)


def main() -> None:
    sys.exit(run(RUST))
